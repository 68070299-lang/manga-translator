import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import type { UserManifest } from 'wxt';
import bookwalkerCorsRules from '../../extension/public/rules/bookwalker-cors.json' with {
  type: 'json',
};
import packageJson from '../../package.json' with { type: 'json' };
import { UNPACKED_EXTENSION_ID, UNPACKED_EXTENSION_KEY } from '../../scripts/extension-key.ts';
import { FORBIDDEN_PERMISSIONS, PERMISSION_BUDGET } from '../../scripts/validate-extension.ts';
import wxtConfig from '../../wxt.config.ts';

/**
 * The manifest is generated by WXT from `wxt.config.ts` plus the entrypoint
 * definitions. These assertions run against the config's manifest object (the
 * source of truth), and, when `dist/chrome-mv3` has been built, against the
 * generated manifest as well.
 */
const configuredManifest = wxtConfig.manifest;
if (
  typeof configuredManifest !== 'object' ||
  configuredManifest === null ||
  configuredManifest instanceof Promise
) {
  throw new Error('wxt.config.ts must declare `manifest` as a plain object for these tests');
}
const manifest: UserManifest = configuredManifest;

interface BuiltManifest {
  version: string;
  permissions: string[];
  host_permissions: string[];
  externally_connectable?: unknown;
  web_accessible_resources?: unknown;
  minimum_chrome_version: string;
  action: { default_popup?: string };
  background: { service_worker: string };
  content_scripts: Array<{ matches: string[]; js: string[]; run_at?: string }>;
  declarative_net_request: { rule_resources: unknown[] };
  key?: string;
}

function readBuiltManifest(...segments: string[]): BuiltManifest | null {
  const file = path.join(import.meta.dirname, '..', '..', 'dist', ...segments, 'manifest.json');
  return fs.existsSync(file) ? (JSON.parse(fs.readFileSync(file, 'utf8')) as BuiltManifest) : null;
}

// dist/chrome-mv3 is the promoted unpacked build; dist/.build/chrome-mv3 is the
// validated staging build that `wxt zip` packs.
const builtManifest = readBuiltManifest('chrome-mv3');
const stagedManifest = readBuiltManifest('.build', 'chrome-mv3');

describe('build output in CI', () => {
  // CI builds before the unit tests, so there a missing build is a failure,
  // not a reason to skip the generated-manifest checks below.
  it.runIf(Boolean(process.env.CI))('exists, so the generated-manifest checks run', () => {
    expect(builtManifest).not.toBeNull();
    expect(stagedManifest).not.toBeNull();
  });
});

describe('unpacked extension ID', () => {
  it('is the ID Chrome derives from the fixed key', () => {
    // Chrome: first 128 bits of SHA-256 over the DER public key, hex digits mapped to a-p.
    const digest = createHash('sha256')
      .update(Buffer.from(UNPACKED_EXTENSION_KEY, 'base64'))
      .digest('hex');
    const id = [...digest.slice(0, 32)]
      .map((digit) => String.fromCharCode(97 + Number.parseInt(digit, 16)))
      .join('');
    expect(id).toBe(UNPACKED_EXTENSION_ID);
  });

  it('keeps the key out of the configured manifest, since store uploads reject it', () => {
    expect(manifest).not.toHaveProperty('key');
  });

  it.runIf(builtManifest !== null)('is pinned in the unpacked build', () => {
    expect(builtManifest?.key).toBe(UNPACKED_EXTENSION_KEY);
  });

  it.runIf(stagedManifest !== null)('is absent from the staging build that gets zipped', () => {
    expect(stagedManifest).not.toHaveProperty('key');
  });
});

describe('extension manifest (wxt.config.ts)', () => {
  it('allows persistent storage for a five-page rendered translation cache', () => {
    expect(manifest.permissions).toContain('storage');
    expect(manifest.permissions).toContain('unlimitedStorage');
  });

  it('pins the permission budget so widening it is a deliberate change', () => {
    const budget = {
      permissions: ['contextMenus', 'declarativeNetRequest', 'storage', 'unlimitedStorage'],
      host_permissions: ['<all_urls>'],
      externally_connectable: undefined,
      web_accessible_resources: undefined,
    };
    const actual = {
      permissions: [...(manifest.permissions ?? [])].sort(),
      host_permissions: manifest.host_permissions,
      externally_connectable: manifest.externally_connectable,
      web_accessible_resources: manifest.web_accessible_resources,
    };

    try {
      expect(actual).toEqual(budget);
    } catch (error) {
      if (error instanceof Error) {
        error.message =
          'Manifest permission budget changed. If this is intentional, update the budget in ' +
          'tests/unit/manifest.test.ts and scripts/validate-extension.ts deliberately and ' +
          `review why the new access is needed. ${error.message}`;
      }
      throw error;
    }
  });

  it('never requests tabs, scripting, or activeTab', () => {
    for (const permission of FORBIDDEN_PERMISSIONS) {
      expect(manifest.permissions).not.toContain(permission);
    }
    expect([...(manifest.permissions ?? [])].sort()).toEqual([...PERMISSION_BUDGET].sort());
  });

  it('declares a minimum Chrome version for the APIs the extension relies on', () => {
    expect(Number(manifest.minimum_chrome_version)).toBeGreaterThanOrEqual(110);
  });

  it('registers a narrowly scoped BookWalker CORS ruleset', () => {
    expect(manifest.declarative_net_request?.rule_resources).toContainEqual({
      id: 'bookwalker_cors',
      enabled: true,
      path: 'rules/bookwalker-cors.json',
    });

    expect(bookwalkerCorsRules).toHaveLength(1);
    const [rule] = bookwalkerCorsRules;
    expect(rule?.condition).toEqual({
      urlFilter: '|https://bw-bv-epubs.bookwalker.jp/',
      initiatorDomains: ['viewer.bookwalker.jp'],
      requestDomains: ['bw-bv-epubs.bookwalker.jp'],
      requestMethods: ['get'],
      resourceTypes: ['xmlhttprequest'],
    });
    expect(rule?.action).toEqual({
      type: 'modifyHeaders',
      requestHeaders: [
        {
          header: 'Referer',
          operation: 'set',
          value: 'https://viewer.bookwalker.jp/',
        },
      ],
      responseHeaders: [
        {
          header: 'Access-Control-Allow-Origin',
          operation: 'set',
          value: 'https://viewer.bookwalker.jp',
        },
      ],
    });
  });
});

describe.skipIf(builtManifest === null)('generated manifest (dist/chrome-mv3)', () => {
  const built = builtManifest as BuiltManifest;

  it('keeps the manifest version in sync with package.json', () => {
    expect(built.version).toBe(packageJson.version);
  });

  it('matches the configured permission budget and host access', () => {
    expect([...built.permissions].sort()).toEqual([...PERMISSION_BUDGET].sort());
    expect(built.host_permissions).toEqual(['<all_urls>']);
    expect(built.externally_connectable).toBeUndefined();
    expect(built.web_accessible_resources).toBeUndefined();
  });

  it('declares the Chrome floor and the bundled DNR ruleset', () => {
    expect(Number(built.minimum_chrome_version)).toBeGreaterThanOrEqual(110);
    expect(built.declarative_net_request.rule_resources).toContainEqual({
      id: 'bookwalker_cors',
      enabled: true,
      path: 'rules/bookwalker-cors.json',
    });
  });

  it('injects one bundled content script on all URLs at document_idle', () => {
    expect(built.content_scripts).toHaveLength(1);
    const [entry] = built.content_scripts;
    expect(entry?.matches).toEqual(['<all_urls>']);
    expect(entry?.run_at).toBe('document_idle');
    expect(entry?.js).toEqual(['content-scripts/content.js']);
  });

  it('wires the popup and the module service worker', () => {
    expect(built.action.default_popup).toBe('popup.html');
    expect(built.background.service_worker).toBe('background.js');
  });
});
